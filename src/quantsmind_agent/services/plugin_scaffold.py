"""Plugin scaffolding (WP v1.7).

Generates a new plugin directory from the alpha manifest + example entrypoint.
No code runs; output is reviewable source.
"""

from __future__ import annotations

from pathlib import Path

__all__ = ["scaffold_plugin"]


_MANIFEST = '{"id": "@PID@", "name": "@PID@", "permissions": ["READ_WORKSPACE"], "entrypoint": "@PID@:tools"}'
_EXAMPLE = '''"""Example plugin tools (scaffold)."""


def tools():
    return [{"name": "@PID@_hello", "description": "example"}]
'''


def scaffold_plugin(destination: str | Path, plugin_id: str) -> Path:
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    pid = plugin_id.strip() or "plugin"
    (destination / "manifest.json").write_text(_MANIFEST.replace("@PID@", pid) + "\n", encoding="utf-8")
    (destination / f"{pid}.py").write_text(_EXAMPLE.replace("@PID@", pid), encoding="utf-8")
    (destination / "README.md").write_text(
        f"# {pid} plugin\n\nGenerated by QuantsMind-Agent v1.7 scaffolding.\n", encoding="utf-8"
    )
    return destination
